#!/usr/bin/env python3
"""Derive config/fish-requirements.lock.txt from the pinned mlx-audio uv.lock.

The Fish environment (tools/fish-venv) installs exactly what upstream locked
for mlx-audio's core dependencies, one wheel per package, hash-checked:

    fish-lock-requirements.py --uv-lock tools/fish-src/mlx-audio/uv.lock \
                              --output config/fish-requirements.lock.txt

Run it with the interpreter the environment will use (python.org 3.12): the
environment markers and the wheel tags are those of the running interpreter.
It walks the root package's core dependencies (no extras, no dev groups),
evaluates each dependency's marker for this interpreter, picks the locked
version, and chooses the most specific compatible wheel by pip's own tag
order. A package without a compatible wheel is an error: nothing may be built
from source. Reads only the lock file; installs nothing.
"""
import argparse
import sys
import tomllib

from pip._vendor.packaging.markers import Marker
from pip._vendor.packaging.tags import sys_tags
from pip._vendor.packaging.utils import canonicalize_name, parse_wheel_filename


def load(path):
    with open(path, "rb") as f:
        lock = tomllib.load(f)
    by_name = {}
    for pkg in lock.get("package", []):
        by_name.setdefault(canonicalize_name(pkg["name"]), []).append(pkg)
    return lock, by_name


def marker_ok(marker, extras=()):
    if not marker:
        return True
    env = {"extra": ""}
    m = Marker(marker)
    if m.evaluate(env):
        return True
    return any(m.evaluate({"extra": e}) for e in extras)


def pick(by_name, dep):
    """The locked package entry a dependency refers to, for this interpreter."""
    cands = by_name.get(canonicalize_name(dep["name"])) or []
    if "version" in dep:
        cands = [p for p in cands if p.get("version") == dep["version"]]
    if len(cands) > 1:
        cands = [p for p in cands
                 if any(marker_ok(m) for m in p.get("resolution-markers", [""]))]
    if len(cands) != 1:
        raise SystemExit(f"cannot resolve {dep} uniquely ({len(cands)} candidates)")
    return cands[0]


def best_wheel(pkg, tag_rank):
    best = None
    for w in pkg.get("wheels", []):
        fname = w["url"].rsplit("/", 1)[-1]
        _, _, _, tags = parse_wheel_filename(fname)
        rank = min((tag_rank[t] for t in tags if t in tag_rank), default=None)
        if rank is not None and (best is None or rank < best[0]):
            best = (rank, fname, w)
    return best


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--uv-lock", required=True)
    ap.add_argument("--output", required=True)
    ap.add_argument("--root", default="mlx-audio")
    a = ap.parse_args()

    lock, by_name = load(a.uv_lock)
    root = pick(by_name, {"name": a.root})
    tag_rank = {t: i for i, t in enumerate(sys_tags())}

    selected, queue = {}, list(root.get("dependencies", []))
    while queue:
        dep = queue.pop(0)
        if not marker_ok(dep.get("marker")):
            continue
        pkg = pick(by_name, dep)
        key = canonicalize_name(pkg["name"])
        extras = tuple(dep.get("extra", []))
        if key in selected:
            if set(extras) <= selected[key][1]:
                continue
            selected[key] = (pkg, selected[key][1] | set(extras))
        else:
            selected[key] = (pkg, set(extras))
        queue.extend(d for d in pkg.get("dependencies", []))
        for e in extras:
            queue.extend(pkg.get("optional-dependencies", {}).get(e, []))

    lines = [
        "# Generated by scripts/fish-lock-requirements.py from the uv.lock of",
        "# cguldogan/mlx-audio @ e7488935ec2ebfafd38ef2b58e290d79f3d05dc7",
        f"# for {sys.implementation.name} {sys.version.split()[0]} on this platform.",
        "# One wheel per package; install with:",
        "#   pip install --require-hashes --no-deps --only-binary=:all: -r <this file>",
    ]
    for key in sorted(selected):
        pkg, _ = selected[key]
        best = best_wheel(pkg, tag_rank)
        if best is None:
            raise SystemExit(f"no compatible wheel locked for {pkg['name']} {pkg['version']}")
        _, fname, w = best
        lines.append(f"{pkg['name']}=={pkg['version']} \\")
        lines.append(f"    --hash={w['hash']}")
        lines.append(f"    # {fname}")
    with open(a.output, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {a.output}: {len(selected)} packages")


if __name__ == "__main__":
    main()
